// 文本归一化。**唯一一份**——判重层和版图层都从这里取。
//
// 为什么单独成文件：判重（lib/dedup.ts）跑在服务端，要 node:crypto 算哈希；
// 版图（lib/market-map.ts）要在浏览器里判断"这两条情报是不是同一份材料"。
// 如果为了让前端能用就照抄一份归一化规则，两份规则迟早分叉——
// 那一天前端会说"两个来源"而后端说"同一份转载"，两个都自称是事实。
// 所以规则只留一份，且这份不许 import 任何 node 内置模块。
//
// 这里只做归一化，不做哈希、不碰数据库、不认识"情报"这个概念。

/**
 * 一个空格，只要它挨着 CJK 字符（左边或右边），就是排版产物而不是词边界。
 * 覆盖：汉字（含扩展A）、中文标点、日文假名、全角形式。
 * 这一步跑在全角折半角之前，所以中文标点此时还是全角形态——全角区间必须列进来。
 * 半角标点挨着汉字的情况（如 "公司, 2025"）由「汉字在另一侧」兜住，不必单独列。
 */
const CJK = [
  "\\u3000-\\u303f",  // 中文标点：。、《》〈〉「」
  "\\u3040-\\u30ff",  // 日文假名
  "\\u3400-\\u4dbf",  // 汉字扩展 A
  "\\u4e00-\\u9fff",  // 汉字基本区
  "\\uf900-\\ufaff",  // 兼容汉字
  // 全角标点。刻意跳过 ０-９、Ａ-Ｚ、ａ-ｚ：
  // 全角字母数字之间的空格是真词边界，"ＡＢ Ｃ" 不能折成 "ABC"。
  "\\uff00-\\uff0f", "\\uff1a-\\uff20", "\\uff3b-\\uff40", "\\uff5b-\\uffef",
].join("");
const CJK_ADJACENT_SPACE = new RegExp(`(?<=[${CJK}]) | (?=[${CJK}])`, "g");

/**
 * 归一化：把"同一份文本的不同排版"折叠成同一个形态。
 * 处理的是转载时真实会变的东西——空白、全角标点、零宽字符、大小写。
 *
 * 刻意不做近似匹配（编辑距离、shingle、向量相似度）：那类分数会长出一个
 * "像不像"的百分比，而百分比一旦显示出来就会被当成判断依据。
 * 这里只做一件能说清楚的事——逐字相同（忽略排版）就是同一份。
 * 代价是明知的：转载时被加了一段编者按，就认不出来。这是已知边界，不是 bug。
 */
export function normalizeCorpus(text: string): string {
  return text
    // 零宽字符与软连字符：复制粘贴的常见残留
    .replace(/[​-‍⁠﻿­]/g, "")
    // 各种空白（含全角空格、不换行空格）先折成一个普通空格
    .replace(/[\s　 ]+/g, " ")
    // 再把紧贴 CJK 的空白整个删掉。
    // 折成一个空格只统一了空白的样子，没解决“有没有空白”：
    // 原文的 "，" 和转载版的 "， " 折完仍然不同，指纹照样被打散——
    // 而排版重排动的恰恰就是这个。
    // 中文里空白不表义（"北京 上海" 与 "北京上海" 读起来是一回事），删掉是安全的。
    // 拉丁词之间的空格保留：那里空格是词边界，"A B" 和 "AB" 不是一回事。
    //
    // 这一步必须排在全角折半角之前。反过来的话，"，" 先被折成半角 ","，
    // 两侧就都不再是 CJK，"， 2025" 里的空格删不掉——曾经就是这个顺序，
    // 结果同一份披露换个排版指纹就变了，判重形同虚设。
    .replace(CJK_ADJACENT_SPACE, "")
    // 全角 ASCII 折成半角（！→ ! 、Ａ→ A）
    .replace(/[！-～]/g, ch => String.fromCharCode(ch.charCodeAt(0) - 0xFEE0))
    .trim()
    .toLowerCase();
}
